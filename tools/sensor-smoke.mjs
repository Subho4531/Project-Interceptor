import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';

const base = process.env.TRAINER_QA_URL ?? 'http://127.0.0.1:4181';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errors = [];
page.on('pageerror', error => errors.push(String(error)));
await page.goto(base + '/trainer?qa=1');
await page.waitForFunction(() => window.__sessionQA?.snapshot().assetsReady, undefined, { timeout: 60000 });
await page.getByRole('heading', { name: /Monitor the post/ }).waitFor({ timeout: 30000 });
await page.getByRole('button', { name: /Start exercise/ }).click();
await page.evaluate(() => window.__sessionQA.command({ type: 'step', seconds: 30 }));
const before = await page.evaluate(() => window.__sessionQA.exercise());
assert.ok(before.tracks.length > 0, 'radar produced a trainee-visible contact');
assert.equal(JSON.stringify(before).includes('sketchfab-fpv'), false);
assert.equal(JSON.stringify(before).includes('aerial-01'), false);
await page.evaluate(() => window.__sessionQA.command({ type: 'resume' }));
await page.getByRole('button', { name: 'Acknowledge track' }).click();
await page.getByRole('button', { name: /Cue EO \/ thermal/ }).click();
await page.locator('.eo-live-panel[data-ready="true"]').waitFor({ timeout: 60000 });
assert.equal(await page.locator('.eo-thermal-canvas').count(), 1);
await page.getByRole('button', { name: 'Close EO live view' }).click();
await page.getByRole('button', { name: /Check RF/ }).click();
await page.getByRole('button', { name: /Check flight roster/ }).click();
await page.getByRole('button', { name: /Movement history/ }).click();
await page.evaluate(() => window.__sessionQA.command({ type: 'step', seconds: 8 }));
await page.evaluate(() => window.__sessionQA.command({ type: 'resume' }));
await mkdir('artifacts/qa/sensor', { recursive: true });
await page.screenshot({ path: 'artifacts/qa/sensor/basic-console.png' });
await page.getByLabel('Object type').selectOption('uav');
await page.getByLabel('Coordination').selectOption('single');
await page.getByLabel('Affiliation').selectOption('unconfirmed');
await page.getByLabel('Threat level').selectOption('medium');
await page.getByRole('button', { name: 'Request verification' }).click();
await page.getByRole('button', { name: 'Report to command' }).click();
await page.getByRole('button', { name: 'Request authorization' }).click();
await page.evaluate(() => window.__sessionQA.command({ type: 'step', seconds: 5 }));
await page.evaluate(() => window.__sessionQA.command({ type: 'resume' }));
await page.getByRole('button', { name: 'Request authorized simulated response' }).click();
await page.evaluate(() => window.__sessionQA.command({ type: 'step', seconds: 4 }));
assert.equal((await page.evaluate(() => window.__sessionQA.exercise())).consequences.length, 1);
await page.evaluate(() => window.__sessionQA.command({ type: 'resume' }));
await page.getByRole('button', { name: 'End & review' }).click();
await page.getByRole('heading', { name: 'Exercise complete' }).waitFor();
const final = await page.evaluate(() => window.__sessionQA.exercise());
assert.ok(Number.isFinite(final.review.overall));
assert.ok(final.review.chronology.length > 0);
await page.waitForFunction(async () => {
  const req = indexedDB.open('project-interceptor-training', 1);
  return await new Promise(resolve => {
    req.onerror = () => resolve(false);
    req.onsuccess = () => {
      const get = req.result.transaction('attempts').objectStore('attempts').getAll();
      get.onsuccess = () => resolve(get.result.length > 0);
      get.onerror = () => resolve(false);
    };
  });
}, undefined, { timeout: 10000 });
assert.deepEqual(errors, []);
await page.screenshot({ path: 'artifacts/qa/sensor/basic-aar.png' });
await page.getByRole('button', { name: /Open replay/ }).click();
await page.getByRole('heading', { name: 'After action review' }).waitFor();
await page.getByLabel(/Replay trainee evidence at/).fill('0');
assert.equal(await page.getByRole('heading', { name: 'Evidence available' }).locator('xpath=..').locator('li').count(), 0);
await page.getByLabel(/Replay trainee evidence at/).fill(String(Math.ceil(final.time)));
assert.ok(await page.getByRole('heading', { name: 'Evidence available' }).locator('xpath=..').locator('li').count() > 0);
await page.screenshot({ path: 'artifacts/qa/sensor/basic-replay.png' });
await page.goto(base + '/observer?qa=1');
await page.locator('canvas[aria-label="Interactive border observation environment"]').waitFor();
await page.getByRole('region', { name: 'Session instructions' }).waitFor({ timeout: 30000 });
assert.deepEqual(errors, []);
await writeFile('artifacts/qa/sensor/basic-report.json', JSON.stringify({ browser: browser.version(), evidence: before.tracks.length, review: final.review, errors }, null, 2));
await browser.close();
console.log('Sensor-led exercise PASS');
