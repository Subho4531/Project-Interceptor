import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';

const base = process.env.TRAINER_QA_URL ?? 'http://127.0.0.1:4173';
const channel = process.env.DASHBOARD_QA_BROWSER ?? 'chrome';
const browser = await chromium.launch({ channel, headless: true });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errors = [];
page.on('pageerror', error => errors.push(String(error)));
await page.goto(base + '/trainer?qa=1');
await page.getByRole('button', { name: /Open dashboard/ }).click();
await page.waitForTimeout(1500);
const viaTrainer = { url: page.url(), heading: await page.locator('h1,h2').allTextContents(), errors: [...errors] };
await page.goto(base + '/dashboard?qa=1');
await page.locator('.eo-live-panel[data-ready="true"]').waitFor({ timeout: 60000 });
await page.evaluate(() => window.__sessionQA.command({ type: 'step', seconds: 30 }));
await page.getByRole('region', { name: 'Live sensor wall' }).getByText(/RETURNS/).waitFor();
const direct = { url: page.url(), heading: await page.locator('h1,h2').allTextContents(), radarReports: (await page.evaluate(() => window.__sessionQA.snapshot())).sensorTracks.length, errors: [...errors] };
assert.ok(direct.radarReports > 0, 'radar scope should receive a delayed contact');
assert.equal(await page.locator('.eo-thermal-canvas').count(), 1);
const thermalVariation = await page.locator('.eo-thermal-canvas').evaluate(canvas => {
  const context = canvas.getContext('2d');
  const pixels = context.getImageData(0, 0, canvas.width, canvas.height).data;
  const colours = new Set();
  for (let index = 0; index < pixels.length; index += 160) colours.add(`${pixels[index]},${pixels[index + 1]},${pixels[index + 2]}`);
  return colours.size;
});
assert.ok(thermalVariation > 4, 'thermal visualization contains rendered image detail');
await page.getByRole('button', { name: 'Cue EO to radar return' }).click();
await page.waitForTimeout(500);
const cued = await page.evaluate(() => window.__sessionQA.snapshot().eo);
assert.ok(cued && Number.isFinite(cued.yaw));
await mkdir('artifacts/qa/dashboard-fix', { recursive: true });
await page.screenshot({ path: `artifacts/qa/dashboard-fix/dashboard-${channel}.png` });
await page.getByRole('button', { name: 'Tactical map' }).click();
await page.locator('.dashboard-map').waitFor();
await page.getByRole('button', { name: 'Sensor wall' }).click();
await page.locator('.eo-live-panel[data-ready="true"]').waitFor({ timeout: 60000 });
await writeFile(`artifacts/qa/dashboard-fix/diagnostic-${channel}.json`, JSON.stringify({ channel, viaTrainer, direct }, null, 2));
await browser.close();
assert.deepEqual(errors, []);
console.log(JSON.stringify({ channel, viaTrainer, direct }));
